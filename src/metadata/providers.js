/**
 * Built-in metadata providers (S05).
 */

import { readFileSync, statSync } from "node:fs";
import { extname } from "node:path";

/**
 * @type {object}
 */
export const fsExtendedProvider = {
  id: "fs-extended",
  /**
   * @param {object} _meta
   * @returns {boolean}
   */
  supports(_meta) {
    return true;
  },
  /**
   * @param {{ targetPath: string }} ctx
   */
  async extract(ctx) {
    const st = statSync(ctx.targetPath);
    /** @type {object} */
    const data = {
      ino: String(st.ino),
      nlink: st.nlink,
      blocks: st.blocks,
      atimeMs: st.atimeMs,
      mtimeMs: st.mtimeMs,
      ctimeMs: st.ctimeMs,
    };
    if (st.birthtimeMs != null) data.birthtimeMs = st.birthtimeMs;
    return { data };
  },
};

/**
 * @type {object}
 */
export const embeddedTextProvider = {
  id: "embedded-text",
  /**
   * @param {object} meta
   * @returns {boolean}
   */
  supports(meta) {
    const ext = (meta.ext ?? "").toLowerCase();
    return [".js", ".mjs", ".cjs", ".ts", ".txt", ".md"].includes(ext) || ext === "";
  },
  /**
   * @param {{ targetPath: string }} ctx
   */
  async extract(ctx) {
    let text;
    try {
      text = readFileSync(ctx.targetPath, "utf8");
    } catch {
      return { skip: true, reason: "extract-failed" };
    }
    const lines = text.split(/\r?\n/).slice(0, 40);
    /** @type {{ kind: string, value: string, loc: { line: number, column: number } }[]} */
    const markers = [];

    for (let i = 0; i < lines.length; i += 1) {
      const line = lines[i];
      const license = line.match(/@license\s+(\S+)/i);
      if (license) {
        markers.push({
          kind: "license",
          value: license[1],
          loc: { line: i + 1, column: 0 },
        });
      }
      const overview = line.match(/@fileoverview\s+(.+)/i);
      if (overview) {
        markers.push({
          kind: "fileoverview",
          value: overview[1].trim(),
          loc: { line: i + 1, column: 0 },
        });
      }
      const generated = line.match(/generated by\s+(.+)/i);
      if (generated) {
        markers.push({
          kind: "generated",
          value: generated[1].trim(),
          loc: { line: i + 1, column: 0 },
        });
      }
    }

    return { data: { markers } };
  },
};

/**
 * Stub EXIF — JS files unsupported.
 * @type {object}
 */
export const exifStubProvider = {
  id: "exif",
  /**
   * @param {object} meta
   * @returns {boolean}
   */
  supports(meta) {
    const ext = (meta.ext ?? "").toLowerCase();
    return [".jpg", ".jpeg", ".png", ".webp", ".tiff"].includes(ext);
  },
  /**
   * @returns {Promise<{ skip: true, reason: string }>}
   */
  async extract() {
    return { skip: true, reason: "not-implemented" };
  },
};

/**
 * @param {string} targetPath
 * @returns {object}
 */
export function fileMeta(targetPath) {
  return { ext: extname(targetPath), path: targetPath };
}
